    (
      status = 'draft'
      AND completed_by IS NULL
      AND completed_at IS NULL
    )
    OR
    (
      status = 'completed'
      AND completed_by IS NOT NULL
      AND completed_at IS NOT NULL
      AND form_config_snapshot IS NOT NULL
      AND form_config_snapshot <> 'null'::JSONB
      AND pieces_data IS NOT NULL
      AND pieces_data <> 'null'::JSONB
