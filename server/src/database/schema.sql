  CONSTRAINT fk_dimension_inspections_lot
    FOREIGN KEY (lot_id) REFERENCES public.lots(id)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
  CONSTRAINT fk_dimension_inspections_created_by
    FOREIGN KEY (created_by) REFERENCES public.users(id)
    ON UPDATE CASCADE
    ON DELETE SET NULL,
  CONSTRAINT fk_dimension_inspections_updated_by
    FOREIGN KEY (updated_by) REFERENCES public.users(id)
    ON UPDATE CASCADE
    ON DELETE SET NULL,
  CONSTRAINT fk_dimension_inspections_completed_by
    FOREIGN KEY (completed_by) REFERENCES public.users(id)
    ON UPDATE CASCADE
    ON DELETE SET NULL
