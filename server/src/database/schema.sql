-- BrakeCheck PostgreSQL 17 baseline schema
-- Target: an empty local/test database named brakecheck_pg.
-- This file does not create, drop, truncate, or select a database.
-- Run it only after confirming the current database and migration user.

BEGIN;

DO $migration_guard$
DECLARE
  existing_table_count INTEGER;
BEGIN
  IF current_database() <> 'brakecheck_pg' THEN
    RAISE EXCEPTION 'Schema target must be brakecheck_pg, current database is %.', current_database();
  END IF;

  IF current_user = 'brakecheck_app' THEN
    RAISE EXCEPTION 'Run the schema as a migration owner, not brakecheck_app.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_roles
    WHERE rolname = 'brakecheck_app'
  ) THEN
    RAISE EXCEPTION 'Required application role brakecheck_app does not exist.';
  END IF;

  IF NOT has_schema_privilege(current_user, 'public', 'CREATE') THEN
    RAISE EXCEPTION 'Migration user does not have CREATE privilege on schema public.';
  END IF;

  IF to_regprocedure('public.set_updated_at()') IS NOT NULL THEN
    RAISE EXCEPTION 'Schema target already contains function public.set_updated_at().';
  END IF;

  SELECT COUNT(*)
  INTO existing_table_count
  FROM information_schema.tables
  WHERE table_schema = 'public'
    AND table_type = 'BASE TABLE';

  IF existing_table_count <> 0 THEN
    RAISE EXCEPTION 'Schema target must be empty; found % public tables.', existing_table_count;
  END IF;
END;
$migration_guard$;

CREATE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

-- Stores QC users. Passwords are stored only as one-way hashes.
CREATE TABLE public.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_code VARCHAR(20) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(100) NOT NULL,
  position VARCHAR(100) NOT NULL,
  role TEXT NOT NULL DEFAULT 'officer',
  status TEXT NOT NULL DEFAULT 'active',
  must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
  failed_login_count SMALLINT NOT NULL DEFAULT 0,
  locked_until TIMESTAMP WITH TIME ZONE NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_users_role CHECK (role IN ('head', 'assistant', 'officer')),
  CONSTRAINT chk_users_status CHECK (status IN ('active', 'suspended')),
  CONSTRAINT chk_users_failed_login_count CHECK (failed_login_count >= 0)
);

-- Stores login sessions so logout can revoke a token immediately.
CREATE TABLE public.auth_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_id CHAR(36) NOT NULL UNIQUE,
  user_id INTEGER NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  revoked_at TIMESTAMP WITH TIME ZONE NULL,
  revoke_reason VARCHAR(40) NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_auth_sessions_user
    FOREIGN KEY (user_id) REFERENCES public.users(id)
    ON UPDATE CASCADE
    ON DELETE SET NULL
);

