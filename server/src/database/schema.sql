-- Stores one dimension inspection header per Lot with completed snapshots.
CREATE TABLE public.dimension_inspections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_id INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft',
  inspection_date DATE NULL,
  shift TEXT NULL,
  instrument_codes JSONB NULL,
  rivet_no VARCHAR(50) NULL,
  production_code VARCHAR(50) NULL,
  brake_type TEXT NULL,
  brake_model TEXT NULL,
  rivet_hole_thickness NUMERIC(3,1) NULL,
  sample_count INTEGER NULL,
  form_config_snapshot JSONB NULL,
  pieces_data JSONB NULL,
  created_by INTEGER NULL,
  updated_by INTEGER NULL,
  completed_by INTEGER NULL,
  completed_at TIMESTAMP WITH TIME ZONE NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_dimension_inspections_lot UNIQUE (lot_id),
  CONSTRAINT chk_dimension_inspections_status CHECK (status IN ('draft', 'completed')),
  CONSTRAINT chk_dimension_inspections_shift CHECK (shift IS NULL OR shift IN ('1', '2')),
  CONSTRAINT chk_dimension_inspections_brake_type
    CHECK (brake_type IS NULL OR brake_type IN ('normal', 'taper', 'sheet')),
  CONSTRAINT chk_dimension_inspections_brake_model
    CHECK (brake_model IS NULL OR brake_model IN ('drilled_bored', 'no_hole')),
  CONSTRAINT chk_dimension_sample_count CHECK (sample_count IS NULL OR sample_count > 0),
