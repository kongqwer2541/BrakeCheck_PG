-- Stores production Lots. lot_number comes from Excel Column A and is unique.
CREATE TABLE public.lots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_number VARCHAR(20) NOT NULL UNIQUE,
  lot_pack_barcode VARCHAR(50) NULL,
  lot_packing VARCHAR(50) NULL,
  model_name VARCHAR(200) NULL,
  dimension VARCHAR(100) NULL,
  aci_grade VARCHAR(20) NULL,
  code VARCHAR(20) NULL,
  purchase_order VARCHAR(50) NULL,
  drill_size NUMERIC(6,2) NULL,
  bore_size NUMERIC(6,2) NULL,
  rivet_no VARCHAR(50) NULL,
  production_date DATE NULL,
  quantity INTEGER NOT NULL DEFAULT 0,
  sample_count INTEGER NOT NULL DEFAULT 0,
  remark1 TEXT NULL,
  remark2 TEXT NULL,
  remark3 TEXT NULL,
  manual_reason TEXT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  imported_by INTEGER NULL,
  import_batch_id INTEGER NULL,
  import_source TEXT NOT NULL DEFAULT 'excel',
  voided_by INTEGER NULL,
  voided_at TIMESTAMP WITH TIME ZONE NULL,
  void_reason TEXT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_lots_quantity CHECK (quantity >= 0),
  CONSTRAINT chk_lots_sample_count CHECK (sample_count >= 0),
  CONSTRAINT chk_lots_status CHECK (
    status IN (
      'pending',
      'temp',
      'waiting_pack',
      'waiting_approve',
      'need_fix',
      'approved',
      'ng',
      'void'
    )
  ),
  CONSTRAINT chk_lots_import_source CHECK (import_source IN ('excel', 'manual')),
  CONSTRAINT chk_lots_void_metadata CHECK (
    (
      status = 'void'
      AND voided_by IS NOT NULL
      AND voided_at IS NOT NULL
      AND NULLIF(BTRIM(void_reason), '') IS NOT NULL
    )
    OR
    (
      status <> 'void'
      AND voided_by IS NULL
      AND voided_at IS NULL
      AND void_reason IS NULL
    )
  ),
  CONSTRAINT fk_lots_imported_by
    FOREIGN KEY (imported_by) REFERENCES public.users(id)
    ON UPDATE CASCADE
    ON DELETE SET NULL,
  CONSTRAINT fk_lots_import_batch
    FOREIGN KEY (import_batch_id) REFERENCES public.excel_import_batches(id)
    ON UPDATE CASCADE
    ON DELETE SET NULL,
  CONSTRAINT fk_lots_voided_by
    FOREIGN KEY (voided_by) REFERENCES public.users(id)
    ON UPDATE CASCADE
    ON DELETE SET NULL
);

