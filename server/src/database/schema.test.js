import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';

const schemaUrl = new URL('./schema.sql', import.meta.url);
const schemaSql = await readFile(schemaUrl, 'utf8');
const executableSchemaSql = schemaSql.replace(/^\s*--.*$/gm, '');
const timezoneMigrationUrl = new URL(
  './migrations/postgresql/phase-4-timezone-aware-timestamps.sql',
  import.meta.url
);
const timezoneMigrationSql = await readFile(timezoneMigrationUrl, 'utf8');
const executableTimezoneMigrationSql = timezoneMigrationSql.replace(/^\s*--.*$/gm, '');

const expectedTables = [
  'users',
  'auth_sessions',
  'user_audit_logs',
  'excel_import_batches',
  'lots',
  'lot_audit_logs',
  'lot_attachments',
  'sampling_rules',
  'dimension_instrument_prefixes',
  'form_config',
  'system_setting_audit_logs',
  'dimension_inspections',
  'packing_inspections',
  'dimension_inspection_values'
];

function getTableDefinition(tableName) {
  const match = schemaSql.match(
    new RegExp(`CREATE TABLE public\\.${tableName} \\(([\\s\\S]*?)\\n\\);`, 'i')
  );

  assert.ok(match, `Missing CREATE TABLE for ${tableName}`);
  return match[1];
}

test('PostgreSQL baseline creates exactly the 14 required tables', () => {
  const createdTables = [...schemaSql.matchAll(/CREATE TABLE public\.([a-z_]+)/gi)]
    .map((match) => match[1]);

  assert.deepEqual(createdTables, expectedTables);
});

test('PostgreSQL baseline contains no destructive or MySQL-only commands', () => {
  assert.doesNotMatch(executableSchemaSql, /\b(?:DROP|TRUNCATE|CREATE\s+DATABASE|USE)\b/i);
  assert.doesNotMatch(executableSchemaSql, /\b(?:AUTO_INCREMENT|TINYINT|DATETIME|ENUM)\b|`/i);
});

test('PostgreSQL baseline validates the target and runs in one transaction', () => {
  assert.match(executableSchemaSql, /^\s*BEGIN;/i);
  assert.match(executableSchemaSql, /current_database\(\)\s*<>\s*'brakecheck_pg'/i);
  assert.match(executableSchemaSql, /current_user\s*=\s*'brakecheck_app'/i);
  assert.match(executableSchemaSql, /FROM pg_roles\s+WHERE rolname = 'brakecheck_app'/i);
  assert.match(
    executableSchemaSql,
    /to_regprocedure\('public\.set_updated_at\(\)'\) IS NOT NULL/i
  );
  assert.match(executableSchemaSql, /information_schema\.tables/i);
  assert.match(executableSchemaSql, /has_schema_privilege\(current_user, 'public', 'CREATE'\)/i);
  assert.match(executableSchemaSql, /COMMIT;\s*$/i);
});

test('PostgreSQL baseline uses PostgreSQL identities, JSONB, checks, and timestamps', () => {
  assert.match(schemaSql, /GENERATED BY DEFAULT AS IDENTITY/i);
  assert.match(schemaSql, /\bJSONB\b/i);
  assert.match(schemaSql, /TIMESTAMP WITH TIME ZONE/i);
  assert.doesNotMatch(schemaSql, /TIMESTAMP WITHOUT TIME ZONE/i);
  assert.match(schemaSql, /production_date DATE/i);
  assert.match(schemaSql, /inspection_date DATE/i);
  assert.match(schemaSql, /CONSTRAINT chk_users_role CHECK/i);
  assert.match(schemaSql, /CONSTRAINT chk_lots_status CHECK/i);
  assert.match(schemaSql, /CONSTRAINT chk_form_input_type CHECK/i);
  assert.match(schemaSql, /CONSTRAINT chk_dimension_values_pass_fail\s+CHECK/i);
});

test('timezone migration is limited to the empty local/test database', () => {
  assert.match(executableTimezoneMigrationSql, /^\s*BEGIN;/i);
  assert.match(
    executableTimezoneMigrationSql,
    /current_database\(\)\s*<>\s*'brakecheck_pg'/i
  );
  assert.match(executableTimezoneMigrationSql, /current_user\s*=\s*'brakecheck_app'/i);
  assert.match(executableTimezoneMigrationSql, /to_regclass\(/i);
  assert.match(executableTimezoneMigrationSql, /SELECT EXISTS\s*\(SELECT 1 FROM public\.%I/i);
  assert.match(executableTimezoneMigrationSql, /AT TIME ZONE 'Asia\/Bangkok'/i);
  assert.equal(
    [...executableTimezoneMigrationSql.matchAll(/TYPE TIMESTAMP WITH TIME ZONE/gi)].length,
    25
  );
  assert.doesNotMatch(
    executableTimezoneMigrationSql,
    /\b(?:DROP|TRUNCATE|DELETE|UPDATE|CREATE\s+DATABASE)\b/i
  );
  assert.match(executableTimezoneMigrationSql, /COMMIT;\s*$/i);
});

test('PostgreSQL baseline preserves Lot uniqueness and updated_at behavior', () => {
  assert.match(schemaSql, /lot_number VARCHAR\(20\) NOT NULL UNIQUE/i);
  assert.match(schemaSql, /CREATE FUNCTION public\.set_updated_at\(\)/i);
  assert.doesNotMatch(schemaSql, /CREATE OR REPLACE FUNCTION public\.set_updated_at\(\)/i);

  const updatedAtTriggers = [...schemaSql.matchAll(/CREATE TRIGGER trg_[a-z_]+_updated_at/gi)];
  assert.equal(updatedAtTriggers.length, 7);
});

test('PostgreSQL baseline requires complete metadata when a Lot is void', () => {
  const lotsTable = getTableDefinition('lots');

  assert.match(lotsTable, /CONSTRAINT chk_lots_void_metadata CHECK/i);
  assert.match(
    lotsTable,
    /status = 'void'[\s\S]*voided_by IS NOT NULL[\s\S]*voided_at IS NOT NULL[\s\S]*NULLIF\(BTRIM\(void_reason\), ''\) IS NOT NULL/i
  );
  assert.match(
    lotsTable,
    /status <> 'void'[\s\S]*voided_by IS NULL[\s\S]*voided_at IS NULL[\s\S]*void_reason IS NULL/i
  );
});

test('PostgreSQL baseline requires completion metadata and snapshots', () => {
  const dimensionTable = getTableDefinition('dimension_inspections');
  const packingTable = getTableDefinition('packing_inspections');

  assert.match(dimensionTable, /CONSTRAINT chk_dimension_completion_metadata CHECK/i);
  assert.match(
    dimensionTable,
    /status = 'completed'[\s\S]*completed_by IS NOT NULL[\s\S]*completed_at IS NOT NULL[\s\S]*form_config_snapshot IS NOT NULL[\s\S]*pieces_data IS NOT NULL/i
  );
  assert.match(packingTable, /CONSTRAINT chk_packing_completion_metadata CHECK/i);
  assert.match(
    packingTable,
    /status = 'completed'[\s\S]*completed_by IS NOT NULL[\s\S]*completed_at IS NOT NULL[\s\S]*form_config_snapshot IS NOT NULL[\s\S]*results_data IS NOT NULL/i
  );
});

test('PostgreSQL baseline grants runtime access without granting schema creation', () => {
  assert.match(
    schemaSql,
    /GRANT SELECT ON ALL TABLES IN SCHEMA public TO brakecheck_app/i
  );
  assert.match(
    schemaSql,
    /GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO brakecheck_app/i
  );
  assert.match(schemaSql, /GRANT DELETE ON TABLE public\.sampling_rules TO brakecheck_app/i);
  assert.doesNotMatch(schemaSql, /GRANT [^;]*DELETE[^;]*ON ALL TABLES/i);
  assert.doesNotMatch(
    schemaSql,
    /GRANT (?:UPDATE|DELETE)[^;]*public\.(?:user_audit_logs|lot_audit_logs|system_setting_audit_logs)/i
  );
  assert.doesNotMatch(schemaSql, /GRANT\s+(?:CREATE|ALL).*TO brakecheck_app/i);
});
